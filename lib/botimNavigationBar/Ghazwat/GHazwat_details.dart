            ),
          ),
          CustomPaint(painter: _WarMeshPainter(), size: Size.infinite),
          _orb(-0.1 + 0.05 * math.sin(t),       -0.6, 300, _crimson,              0.07),
          _orb(0.5  + 0.04 * math.cos(t * 0.8),  0.3, 220, const Color(0xFF1A3A5C), 0.09),
