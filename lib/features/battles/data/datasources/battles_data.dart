رابعاً: مسير الجيش وبطولة أسامة
خرج الصديق رضي الله عنه يودع جيش أسامة ماشياً على قدميه وأسامة راكب، فقال أسامة خجلاً: «يا خليفة رسول الله، إما أن تركب وإما أن أنزل!»، فقال أبو بكر بتواضع الصديقين: «واللهِ لا تنزل وواللهِ لا أركب! وما عليّ أن أغبّر قدمي ساعة في سبيل الله؟!».
واستأذن أبو بكر أسامة أن يترك له عمر بن الخطاب في المدينة ليعينه في أمر الخلافة، فأذن له أسامة.
ومضى أسامة بالجيش يجدّ السير فقطع الجزيرة إلى أرض فلسطين في عشرين ليلة، وباغت أعداءه في «أُبْنى» وشن الغارة عليهم مع الفجر، وهزم حاميات الروم وحلفاءهم هزيمة منكرة، وقاتل أسامة على فرس أبيه زيد حتى قتل قاتل أبيه، وغنم المسلمون غنائم عظيمة وعادوا دون أن يُقتل منهم رجل واحد!

خامساً: الآثار الاستراتيجية الكبرى
كان لخروج وعودة جيش أسامة أثر نفسي وسياسي هائل؛ فقالت قبائل العرب المرتدة في دهشة ورعب: «والله ما خرج هذا الجيش إلا والمدينة تملك قوة عارمة وجيوشاً لا قِبل لنا بها! لو كان بهم ضعف ما خرجت هذه الجيوش إلى تخوم الروم!»؛ فثبت من ثبت على الإسلام وخافت قبائل كثيرة.
وعاد أسامة إلى المدينة بعد غيبة أربعين يوماً رافعاً اللواء النبوي، ودخل المسجد فصلى ركعتين، واستقبله الصديق والمسلمون بالفرح والتكبير، فكان إنفاذ جيش أسامة مفتاح تثبيت الدولة الإسلامية وبداية انطلاق فتوحات الشام الكبرى.

